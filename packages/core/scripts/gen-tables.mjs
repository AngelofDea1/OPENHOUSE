// Single source of truth for the payout tables of Wheel, Plinko and Keno.
// The formulas are the ones the site has always used. Run once, commit the output:
//   node scripts/gen-tables.mjs
// It writes programs/openhouse/src/games/tables.rs and packages/core/src/tables.ts (same numbers, multipliers x100).
import { writeFileSync } from 'node:fs';
const WN = 24;
function wheelSegs(risk) {
  const a = Array(WN).fill(0);
  if (risk === 0) { for (let i = 0; i < WN; i++) a[i] = i % 4 === 0 ? 1.5 : (i % 4 === 1 || i % 4 === 3) ? 1.2 : 0; }
  else if (risk === 1) { for (let i = 0; i < WN; i++) a[i] = i % 6 === 5 ? 3 : (i % 6 === 1 || i % 6 === 3) ? 1.5 : 0; }
  else { [2, 7, 11, 14, 19, 22].forEach((i) => (a[i] = 3)); a[4] = 10; a[16] = 10; a[9] = 0; }
  const mean = a.reduce((x, y) => x + y, 0) / WN, c = 0.99 / mean;
  return a.map((v) => (v ? Math.round(v * c * 100) / 100 : 0));
}
const binom = (n) => { let r = [1]; for (let i = 0; i < n; i++) { const x = [1]; for (let j = 1; j < r.length; j++) x.push(r[j - 1] + r[j]); x.push(1); r = x; } return r; };
function plinkoTable(n, risk) {
  const s = { low: 1.5, med: 3, high: 4.8 }[risk], b = binom(n), pr = b.map((x) => x / Math.pow(2, n));
  const g = (k) => Math.exp(s * Math.pow(Math.abs(k - n / 2) / (n / 2), 1.7));
  let ev = 0; pr.forEach((p, k) => (ev += p * g(k)));
  const c = 0.99 / ev;
  return pr.map((_, k) => Math.round(c * g(k) * 100) / 100);
}
const nCr = (n, k) => { if (k < 0 || k > n) return 0; let r = 1; for (let i = 1; i <= k; i++) r = r * (n - k + i) / i; return r; };
const kenoTable = (n) => {
  const t = Math.floor(n * 0.3), g = (h) => (h > t ? Math.pow(h - t, 2.2) : 0), p = (h) => nCr(n, h) * nCr(40 - n, 10 - h) / nCr(40, 10);
  let s = 0; for (let h = 0; h <= n; h++) s += p(h) * g(h);
  const c = 0.99 / s;
  return Array.from({ length: n + 1 }, (_, h) => Math.min(500, Math.round(c * g(h) * 100) / 100));
};
const x100 = (a) => a.map((v) => Math.round(v * 100));
const T = { wheel: [0, 1, 2].map((r) => x100(wheelSegs(r))), plinko: {}, keno: [] };
for (const rows of [8, 10, 12, 14, 16]) T.plinko[rows] = ['low', 'med', 'high'].map((k) => x100(plinkoTable(rows, k)));
for (let n = 1; n <= 10; n++) T.keno.push(x100(kenoTable(n)));

// exact RTP of the rounded tables, reported so nothing hides behind rounding
const rtp = {};
rtp.wheel = T.wheel.map((t) => t.reduce((a, b) => a + b, 0) / WN / 100);
rtp.plinko = {}; for (const rows of Object.keys(T.plinko)) rtp.plinko[rows] = T.plinko[rows].map((t) => { const b = binom(+rows); return t.reduce((s, m, k) => s + m / 100 * b[k] / Math.pow(2, +rows), 0); });
rtp.keno = T.keno.map((t, i) => { const n = i + 1; return t.reduce((s, m, h) => s + m / 100 * nCr(n, h) * nCr(40 - n, 10 - h) / nCr(40, 10), 0); });
console.log(JSON.stringify(rtp));

const arr = (a) => '&[' + a.join(', ') + ']';
let rs = '// GENERATED by packages/core/scripts/gen-tables.mjs, do not edit. Multipliers are x100 of the stake, total payout.\n';
rs += `pub const WHEEL: [[u32; 24]; 3] = [${T.wheel.map((t) => '[' + t.join(', ') + ']').join(', ')}];\n`;
rs += `pub const PLINKO_ROWS: [u8; 5] = [8, 10, 12, 14, 16];\n`;
rs += `/// PLINKO[row index][risk 0 low, 1 med, 2 high] -> multipliers per landing slot (rows + 1 values)\n`;
rs += `pub const PLINKO: [[&[u32]; 3]; 5] = [${[8, 10, 12, 14, 16].map((r) => '[' + T.plinko[r].map(arr).join(', ') + ']').join(',\n    ')}];\n`;
rs += `/// KENO[picks - 1] -> multipliers by number of hits (picks + 1 values)\n`;
rs += `pub const KENO: [&[u32]; 10] = [${T.keno.map(arr).join(',\n    ')}];\n`;
writeFileSync('../../programs/openhouse/src/games/tables.rs', rs);
let ts = '// GENERATED by scripts/gen-tables.mjs, do not edit. Multipliers are x100 of the stake, total payout.\n';
ts += `export const WHEEL: number[][] = ${JSON.stringify(T.wheel)};\n`;
ts += `export const PLINKO_ROWS = [8, 10, 12, 14, 16];\n`;
ts += `export const PLINKO: Record<number, number[][]> = ${JSON.stringify(T.plinko)};\n`;
ts += `export const KENO: number[][] = ${JSON.stringify(T.keno)};\n`;
writeFileSync('src/tables.ts', ts);
